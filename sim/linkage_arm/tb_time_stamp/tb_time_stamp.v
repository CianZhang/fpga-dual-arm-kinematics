`timescale 1ns/1ns

module tb_time_stamp;

// ******************************************************************** //
// ********************* Signal Declarations ************************** //
// ******************************************************************** //

reg             sys_clk;
reg             sys_rst_n;
reg             i_stamp;

wire [7:0]      sm_seg;
wire [3:0]      sm_bit;

wire [15:0]     o_time;
wire [15:0]     o_cnt;

// ******************************************************************** //
// ******************** Instantiation of the DUT ********************** //
// ******************************************************************** //

time_stamp uut (
    .sys_clk(sys_clk),
    .sys_rst_n(sys_rst_n),
    .i_stamp(i_stamp),
    .sm_seg(sm_seg),
    .sm_bit(sm_bit),
    .o_time(o_time),
    .o_cnt(o_cnt)
);

// ******************************************************************** //
// ********************* Clock Generation **************************** //
// ******************************************************************** //

initial begin
    sys_clk = 0;
end

always #2 sys_clk = ~sys_clk;  // 24MHz时钟的近似信号，半周期为21ns

// ******************************************************************** //
// ************************ Testbench Code **************************** //
// ******************************************************************** //

initial begin
    // 初始化信号
    sys_clk = 0;
    sys_rst_n = 0;
    i_stamp = 0;
    
    // 复位
    #20;
    sys_rst_n = 1;
    
    #5000;
    #5000;

    #500000000;
    i_stamp = 1;
    #5000;
    #5000;
    #5000;
    #5000;
    #5000;
    #5000;
    #5000;
    i_stamp = 0;
    #500000000;
    
    #500000000;
    i_stamp = 1;
    #5000;
    #5000;
    #5000;
    #5000;
    #5000;
    #5000;
    #5000;
    i_stamp = 0;
    #500000000;
    
    // 停止仿真
    $stop;
end

endmodule
