`timescale 1ns/1ps

module tb_cordic_serial;

// ******************************************************************** //
// ********************* Signal Declarations ************************** //
// ******************************************************************** //

reg sys_clk;
reg sys_rst_n;
reg signed [17:0] x;
reg signed [17:0] y;

wire [24:0] phase;
wire        valid;
// ******************************************************************** //
// ******************** Instantiation of the DUT ********************** //
// ******************************************************************** //

cordic_serial uut (
    .x(x),
    .y(y),
    .sys_clk(sys_clk),
    .sys_rst_n(sys_rst_n),
    .phase(phase),
    .valid(valid)
);

// ******************************************************************** //
// ********************* Clock Generation **************************** //
// ******************************************************************** //

initial begin
    sys_clk = 0;
end

always #21 sys_clk = ~sys_clk;  // 24MHz时钟的近似信号，半周期为21ns

// ******************************************************************** //
// ************************ Testbench Code **************************** //
// ******************************************************************** //


initial begin
    // 初始化所有输入信号
    x = 0;
    y = 0;
    sys_rst_n = 0;

    // 复位系统，保持复位信号低电平20ns
    #20;
    sys_rst_n = 1;  // 释放复位信号

        y = -32'd56755;      //sin300
        x = 32'd32768;       //cos300
        
        #20000;
        
        y = 32'd32768;       //sin150
        x = -32'd56755;      //cos150
        
        #20000;
        
        y = 32'd32768;       //sin30
        x = 32'd56754;       //cos30
        
        #20000;
        
        y = -32'd53687;      //sin235
        x = -32'd37591;      //cos235
        
        #20000;

        $stop;
    end

endmodule
