`timescale 1ns/1ps

module tb_sqrt;

// ******************************************************************** //
// ********************* Signal Declarations ************************** //
// ******************************************************************** //

reg sys_clk;
reg sys_rst_n;

reg  [31:0] data;

wire [15:0] sqrt;
wire        valid;
// ******************************************************************** //
// ******************** Instantiation of the DUT ********************** //
// ******************************************************************** //

sqrt uut (
    .sys_clk(sys_clk),
    .sys_rst_n(sys_rst_n),
    .data(data),
    .sqrt(sqrt),
    .valid(valid)
);

// ******************************************************************** //
// ********************* Clock Generation **************************** //
// ******************************************************************** //

initial begin
    sys_clk = 0;
end

always #21 sys_clk = ~sys_clk;  // 24MHz时钟的近似信号，半周期为21ns

// ******************************************************************** //
// ************************ Testbench Code **************************** //
// ******************************************************************** //


initial begin
    // 初始化所有输入信号
    data = 0;
    sys_rst_n = 0;

    // 复位系统，保持复位信号低电平20ns
    #20;
    sys_rst_n = 1;  // 释放复位信号
       
    data = 32'd1024;
    #20000;
    
    data = 32'd61145;
    #20000;
    
    data = 32'd4500;
    #20000;

    $stop;
end

endmodule
